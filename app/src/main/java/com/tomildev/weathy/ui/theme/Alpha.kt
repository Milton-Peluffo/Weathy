package com.tomildev.weathy.ui.theme

object Alpha {
    /** 1.0f - No transparency. Used for primary content and fully opaque elements. */
    const val AlphaFull = 1.0f

    /** 0.7f - High emphasis. Ideal for important text or active icons. */
    const val AlphaExtraHigh = 0.85f
    const val AlphaHigh = 0.7f

    /** 0.5f - Medium emphasis. Used for secondary text, hints, or inactive states. */
    const val AlphaMedium = 0.5f

    /** 0.3f - Low emphasis. Useful for disabled elements or subtle overlays. */
    const val AlphaLow = 0.3f

    /** 0.12f - Extra low emphasis. Best for dividers, borders, or very light backgrounds. */
    const val AlphaExtraLow = 0.12f
}